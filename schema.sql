CREATE DATABASE IF NOT EXISTS vinylflow
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE vinylflow;

CREATE TABLE IF NOT EXISTS usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol ENUM('admin','comprador') NOT NULL DEFAULT 'comprador',
  activo TINYINT(1) NOT NULL DEFAULT 1,
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vinilos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  titulo VARCHAR(200) NOT NULL,
  artista VARCHAR(150) NOT NULL,
  anio INT NOT NULL,
  sello VARCHAR(150) NOT NULL,
  genero VARCHAR(50) NOT NULL,
  tamano VARCHAR(50) NOT NULL,
  estado VARCHAR(50) NOT NULL,
  stock INT NOT NULL DEFAULT 0,
  precio DECIMAL(10,2) NOT NULL DEFAULT 0,
  imagen VARCHAR(500),
  creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS ventas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL,
  vinilo_id INT NOT NULL,
  titulo_vinilo VARCHAR(200) NOT NULL,
  artista_vinilo VARCHAR(150) NOT NULL,
  precio DECIMAL(10,2) NOT NULL,
  fecha_venta TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (vinilo_id) REFERENCES vinilos(id) ON DELETE CASCADE
);